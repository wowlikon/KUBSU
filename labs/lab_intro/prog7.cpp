#include <iostream>

using namespace std;

int main() {
    double a, b;

    cout << "Enter two numbers: " << endl;
    cout << "A = ";
    cin >> a;
    cout << "B = ";
    cin >> b;

    cout << "A+B = " << a + b << endl;
    cout << "A-B = " << a - b << endl;
    cout << "A*B = " << a * b << endl;
    cout << "A/B = " << a / b << endl;
    return 0;
}
